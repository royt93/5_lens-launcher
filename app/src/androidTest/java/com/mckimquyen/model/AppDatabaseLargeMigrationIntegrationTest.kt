package com.mckimquyen.model

import android.database.sqlite.SQLiteDatabase
import androidx.room.Room
import androidx.test.ext.junit.runners.AndroidJUnit4
import androidx.test.platform.app.InstrumentationRegistry
import kotlinx.coroutines.runBlocking
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import org.junit.runner.RunWith

/**
 * Release check: the v12 -> v13 migration on a DENSE database (many lenses, thousands of rows, every kind of per-app state), not the two-row
 * toy of [AppDatabaseMigrationIntegrationTest]. The v12 tables are built with the exact CREATE statements of app/schemas/.../12.json, rows are
 * generated by a fixed formula, and every migrated row is compared with the same formula. It is still a database made by a test, not one
 * written by a released build.
 */
@RunWith(AndroidJUnit4::class)
class AppDatabaseLargeMigrationIntegrationTest {
    @get:org.junit.Rule val deviceStateGuard = com.mckimquyen.testing.DeviceStateGuard()

    private companion object {
        const val DB = "large-v12-migration-test.db"
        const val V12 = 12
        const val LENSES = 12
        const val APPS_PER_LENS = 250
        const val FAVORITE_EVERY = 7
        const val HIDDEN_EVERY = 5
        const val FOLDER_EVERY = 11
        const val FOLDER_COUNT = 4
        const val ZONE_EVERY = 13
        const val OPENED_EVERY = 3
        const val NOTIFY_EVERY = 17
        const val LENS_CREATED_BASE = 1_000L
        const val CREATE_APP = "CREATE TABLE IF NOT EXISTS `APP_PERSISTENT` (`ID` INTEGER PRIMARY KEY AUTOINCREMENT, `PACKAGE_NAME` TEXT, `NAME` TEXT, `IDENTIFIER` TEXT NOT NULL, `OPEN_COUNT` INTEGER NOT NULL, `ORDER_NUMBER` INTEGER NOT NULL, `APP_VISIBLE` INTEGER NOT NULL, `APP_OPENED` INTEGER NOT NULL, `PALETTE_COLOR` INTEGER NOT NULL DEFAULT 0, `IS_FAVORITE` INTEGER NOT NULL DEFAULT 0, `FOLDER_NAME` TEXT, `PINNED_ZONE` TEXT NOT NULL DEFAULT 'NONE', `LENS_ID` TEXT NOT NULL DEFAULT 'default', `NOTIFICATION_COUNT` INTEGER NOT NULL DEFAULT 0)"
        const val CREATE_INDEX = "CREATE UNIQUE INDEX IF NOT EXISTS `index_APP_PERSISTENT_LENS_ID_IDENTIFIER` ON `APP_PERSISTENT` (`LENS_ID`, `IDENTIFIER`)"
        const val CREATE_LENS = "CREATE TABLE IF NOT EXISTS `LENS_WORKSPACE` (`ID` TEXT NOT NULL, `NAME` TEXT NOT NULL, `ORDER_INDEX` INTEGER NOT NULL DEFAULT 0, `CREATED_AT` INTEGER NOT NULL DEFAULT 0, PRIMARY KEY(`ID`))"
    }

    private fun lensId(l: Int) = if (l == 0) LensWorkspace.DEFAULT_LENS_ID else "lens$l"
    private fun identifier(l: Int, a: Int) = "com.big.app$a-Main"
    private fun zone(a: Int) = if (a % ZONE_EVERY == 0) (if (a % 2 == 0) "START" else "END") else "NONE"
    private fun folder(a: Int): String? = if (a % FOLDER_EVERY == 0) "Folder${a % FOLDER_COUNT}" else null

    @Test fun denseV12DatabaseMigratesEveryRowAndLensUnchanged() = runBlocking {
        val context = InstrumentationRegistry.getInstrumentation().targetContext
        context.deleteDatabase(DB)
        val file = context.getDatabasePath(DB).also { it.parentFile?.mkdirs() }
        SQLiteDatabase.openOrCreateDatabase(file, null).use { db ->
            db.execSQL(CREATE_APP); db.execSQL(CREATE_INDEX); db.execSQL(CREATE_LENS)
            db.beginTransaction()
            try {
                for (l in 0 until LENSES) db.execSQL("INSERT INTO LENS_WORKSPACE (ID, NAME, ORDER_INDEX, CREATED_AT) VALUES ('${lensId(l)}', 'Lens $l', $l, ${LENS_CREATED_BASE + l})")
                for (l in 0 until LENSES) for (a in 0 until APPS_PER_LENS) {
                    val folder = folder(a)?.let { "'$it'" } ?: "NULL"
                    db.execSQL(
                        "INSERT INTO APP_PERSISTENT (PACKAGE_NAME, NAME, IDENTIFIER, OPEN_COUNT, ORDER_NUMBER, APP_VISIBLE, APP_OPENED, PALETTE_COLOR, IS_FAVORITE, FOLDER_NAME, PINNED_ZONE, LENS_ID, NOTIFICATION_COUNT) VALUES " +
                            "('com.big.app$a', 'Main', '${identifier(l, a)}', ${a + l}, ${a * 2 + l}, ${if (a % HIDDEN_EVERY == 0) 0 else 1}, ${if (a % OPENED_EVERY == 0) 1 else 0}, ${a * 31 + l}, ${if (a % FAVORITE_EVERY == 0) 1 else 0}, $folder, '${zone(a)}', '${lensId(l)}', ${if (a % NOTIFY_EVERY == 0) a else 0})"
                    )
                }
                db.setTransactionSuccessful()
            } finally { db.endTransaction() }
            db.version = V12
        }
        val migrated = Room.databaseBuilder(context, AppDatabase::class.java, DB).addMigrations(AppDatabase.MIGRATION_12_13).build()
        try {
            val lenses = migrated.lensWorkspaceDao().getAll()
            assertEquals("every lens must survive", LENSES, lenses.size)
            lenses.forEachIndexed { l, lens ->
                assertEquals(lensId(l), lens.id); assertEquals("Lens $l", lens.name); assertEquals(l, lens.orderIndex)
                assertEquals(LENS_CREATED_BASE + l, lens.createdAt); assertNull("the new group column starts empty", lens.groupName)
            }
            val all = migrated.appPersistentDao().getAllRows()
            assertEquals("every row must survive", LENSES * APPS_PER_LENS, all.size)
            var checked = 0
            for (l in 0 until LENSES) {
                val rows = migrated.appPersistentDao().getAllForLens(lensId(l)).associateBy { it.identifier }
                assertEquals("rows of lens $l", APPS_PER_LENS, rows.size)
                for (a in 0 until APPS_PER_LENS) {
                    val r = requireNotNull(rows[identifier(l, a)]) { "missing row lens=$l app=$a" }
                    assertEquals((a + l).toLong(), r.openCount); assertEquals(a * 2 + l, r.orderNumber)
                    assertEquals(a % HIDDEN_EVERY != 0, r.appVisible); assertEquals(a % OPENED_EVERY == 0, r.appOpened)
                    assertEquals(a % FAVORITE_EVERY == 0, r.isFavorite); assertEquals(folder(a), r.folderName)
                    assertEquals(zone(a), r.pinnedZone); assertEquals(a * 31 + l, r.paletteColor)
                    assertEquals(if (a % NOTIFY_EVERY == 0) a else 0, r.notificationCount); checked++
                }
            }
            assertEquals(LENSES * APPS_PER_LENS, checked)
            assertTrue("positive control: the data really has hidden, favorite, foldered and pinned rows", all.any { !it.appVisible } && all.any { it.isFavorite } && all.any { it.folderName != null } && all.any { it.pinnedZone != PinnedZone.NONE.name })
        } finally { migrated.close(); context.deleteDatabase(DB) }
    }
}
